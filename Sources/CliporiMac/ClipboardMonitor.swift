import AppKit
import ApplicationServices
import CliporiCore

@MainActor
final class ClipboardMonitor {
    struct Source {
        var name: String
        var bundleID: String?
        var processID: pid_t?
    }
    private var timer: Timer?
    private var activationObserver: NSObjectProtocol?
    private var activeSource: Source?
    private var lastChange: Int
    private unowned let model: AppModel
    private let pasteboard: NSPasteboard
    private let loadImage: (String) async throws -> Data?
    private var copyRequest: UUID?
    private let source: () -> Source
    init(model: AppModel, pasteboard: NSPasteboard = .general,
         loadImage: ((String) async throws -> Data?)? = nil, source: @escaping () -> Source = {
        let app = NSWorkspace.shared.frontmostApplication
        return Source(name: app?.localizedName ?? L("剪贴板"), bundleID: app?.bundleIdentifier, processID: app?.processIdentifier)
    }) {
        self.model = model; self.pasteboard = pasteboard; self.source = source
        self.loadImage = loadImage ?? { [store = model.store] in try await store.imageData(attachment: $0) }
        lastChange = pasteboard.changeCount
    }
    func start(observeExternalEvents: Bool = true) {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.2, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.04
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        guard observeExternalEvents else { return }
        activeSource = source()
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated {
                guard let self else { return }
                // Capture pending cut/copy data with the app that produced it before switching source.
                self.poll(from: self.activeSource ?? self.source())
                self.activeSource = self.source()
                self.refreshAccessibilityPermission()
            }
        }
        refreshAccessibilityPermission()
    }
    func stop() {
        timer?.invalidate(); timer = nil
        if let activationObserver { NSWorkspace.shared.notificationCenter.removeObserver(activationObserver) }
        activationObserver = nil
        model.hasAccessibilityPermission = false
    }
    func refreshAccessibilityPermission() {
        model.hasAccessibilityPermission = AXIsProcessTrusted()
    }
    func poll() {
        poll(from: source())
    }
    private func poll(from app: Source) {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        guard model.ready else { return }
        guard !model.preferences.capturePaused, !model.isClearingHistory,
              !model.preferences.ignoredApps.contains(app.bundleID ?? "") else { lastChange = change; return }
        let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !privateTypes.contains(where: { pasteboard.types?.contains(NSPasteboard.PasteboardType($0)) == true }) else { lastChange = change; return }
        // Internal card copies are suppressed by lastChange in copy(). Do not discard editor cuts
        // or an external cut followed immediately by bringing Clipori to the foreground.
        // Screenshots commonly advertise TIFF as well as PNG. Prefer pixels over accompanying alt text.
        let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, .init("public.jpeg")]
        if let type = imageTypes.first(where: { pasteboard.types?.contains($0) == true }), let data = pasteboard.data(forType: type) {
            let record = Memory(body: "", kind: .image, source: app.name, sourceBundleID: app.bundleID)
            lastChange = change
            Task { await model.acceptImage(data, record: record) }
            return
        }
        guard let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let record = Memory(body: text, source: app.name, sourceBundleID: app.bundleID)
        // Do not consume an empty/incomplete pasteboard declaration before its data arrives.
        lastChange = change
        Task { await model.accept(record) }
    }
    @discardableResult
    func copy(_ record: Memory) async -> Bool {
        let request = UUID()
        copyRequest = request
        do {
            let item = NSPasteboardItem()
            if record.kind == .image {
                guard let attachment = record.attachment, let png = try await loadImage(attachment) else { throw ClipboardImageError.missing }
                guard copyRequest == request, !Task.isCancelled else { return false }
                let tiff = try await ClipboardImageProcessor.shared.tiff(from: png)
                item.setData(png, forType: .png); item.setData(tiff, forType: .tiff)
            } else { item.setString(record.body, forType: .string) }
            // Validate/load pixels before clearing, so missing attachments do not destroy the user's clipboard.
            // A slower earlier image must never overwrite the card the user clicked most recently.
            guard copyRequest == request, !Task.isCancelled else { return false }
            pasteboard.clearContents()
            let written = pasteboard.writeObjects([item])
            lastChange = pasteboard.changeCount
            guard written else { throw ClipboardImageError.writeFailed }
            await model.didUse(record)
            return true
        } catch {
            if copyRequest == request, !Task.isCancelled { model.toast(error.localizedDescription) }
            return false
        }
    }
}
