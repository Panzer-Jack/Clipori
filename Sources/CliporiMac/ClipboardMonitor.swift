import AppKit
import CliporiCore

@MainActor
final class ClipboardMonitor {
    struct Source {
        var name: String
        var bundleID: String?
        var processID: pid_t?
    }
    private var timer: Timer?
    private var lastChange: Int
    private unowned let model: AppModel
    private let pasteboard: NSPasteboard
    private let loadImage: (String) async throws -> Data?
    private var copyRequest: UUID?
    private let source: () -> Source
    init(model: AppModel, pasteboard: NSPasteboard = .general,
         loadImage: ((String) async throws -> Data?)? = nil, source: @escaping () -> Source = {
        let app = NSWorkspace.shared.frontmostApplication
        return Source(name: app?.localizedName ?? L("剪贴板"), bundleID: app?.bundleIdentifier, processID: app?.processIdentifier)
    }) {
        self.model = model; self.pasteboard = pasteboard; self.source = source
        self.loadImage = loadImage ?? { [store = model.store] in try await store.imageData(attachment: $0) }
        lastChange = pasteboard.changeCount
    }
    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        timer?.tolerance = 0.1
    }
    func poll() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard model.ready, !model.preferences.capturePaused else { return }
        let app = source()
        guard app.processID != ProcessInfo.processInfo.processIdentifier else { return }
        guard !model.preferences.ignoredApps.contains(app.bundleID ?? "") else { return }
        let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !privateTypes.contains(where: { pasteboard.types?.contains(NSPasteboard.PasteboardType($0)) == true }) else { return }
        // Screenshots commonly advertise TIFF as well as PNG. Prefer pixels over accompanying alt text.
        let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, .init("public.jpeg")]
        if let type = imageTypes.first(where: { pasteboard.types?.contains($0) == true }), let data = pasteboard.data(forType: type) {
            let record = Memory(body: "", kind: .image, source: app.name, sourceBundleID: app.bundleID)
            Task { await model.acceptImage(data, record: record) }
            return
        }
        guard let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let record = Memory(body: text, source: app.name, sourceBundleID: app.bundleID)
        Task { await model.accept(record) }
    }
    @discardableResult
    func copy(_ record: Memory) async -> Bool {
        let request = UUID()
        copyRequest = request
        do {
            let item = NSPasteboardItem()
            if record.kind == .image {
                guard let attachment = record.attachment, let png = try await loadImage(attachment) else { throw ClipboardImageError.missing }
                guard copyRequest == request, !Task.isCancelled else { return false }
                let tiff = try await ClipboardImageProcessor.shared.tiff(from: png)
                item.setData(png, forType: .png); item.setData(tiff, forType: .tiff)
            } else { item.setString(record.body, forType: .string) }
            // Validate/load pixels before clearing, so missing attachments do not destroy the user's clipboard.
            // A slower earlier image must never overwrite the card the user clicked most recently.
            guard copyRequest == request, !Task.isCancelled else { return false }
            pasteboard.clearContents()
            let written = pasteboard.writeObjects([item])
            lastChange = pasteboard.changeCount
            guard written else { throw ClipboardImageError.writeFailed }
            return true
        } catch {
            if copyRequest == request, !Task.isCancelled { model.toast(error.localizedDescription) }
            return false
        }
    }
}
